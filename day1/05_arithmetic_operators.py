# Python mein math calculate karne ke 7 primary operators hote hain.
# =============================================================================

a = 15
b = 4

print("a =", a, ", b =", b)
print("-" * 30)

# 1. Addition (+)
print("a + b  =", a + b)     # 19

# 2. Subtraction (-)
print("a - b  =", a - b)     # 11

# 3. Multiplication (*)
print("a * b  =", a * b)     # 60

# 4. Division (/) -> Humesha float mein answer deta hai
print("a / b  =", a / b)     # 3.75

# 5. Floor Division (//) -> Decimal ke baad ka part hata deta hai
print("a // b =", a // b)    # 3

# 6. Modulus (%) -> Divide karne ke baad jo REMAINDER bachta hai
print("a % b  =", a % b)     # 3 (15 ko 4 se divide karne par 3 bachta hai)

# 7. Exponentiation (**) -> Power (a ki power b)
print("a ** 2 =", a ** 2)    # 15 * 15 = 225
print("2 ** 3 =", 2 ** 3)    # 2 * 2 * 2 = 8
